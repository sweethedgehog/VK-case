const $ = (selector) => document.querySelector(selector);
const state = { sessionId: getSessionId(), busy: false, courses: [], view: 'chat' };

function getSessionId() {
  let id = localStorage.getItem('hse-assistant-session');
  if (!id) {
    id = (crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}-${Math.random().toString(16).slice(2)}`);
    localStorage.setItem('hse-assistant-session', id);
  }
  return `web-${id}`;
}

function escapeHtml(text) {
  return String(text).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
}

function safeUrl(url) {
  try { const parsed = new URL(url); return ['https:', 'http:'].includes(parsed.protocol) ? parsed.href : null; }
  catch { return null; }
}

// Small safe renderer for the subset of Markdown generated by the assistant.
function renderMarkdown(raw) {
  let text = escapeHtml(raw ?? '');
  text = text.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, (_, label, url) => {
    const href = safeUrl(url.replaceAll('&amp;', '&'));
    return href ? `<a href="${escapeHtml(href)}" target="_blank" rel="noopener noreferrer">${label}</a>` : label;
  });
  text = text.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  text = text.replace(/(^|\s)\*(.+?)\*(?=\s|$)/g, '$1<em>$2</em>');
  const lines = text.split('\n');
  let out = '', listType = null;
  for (const line of lines) {
    const bullet = /^\s*[-•]\s+(.+)$/.exec(line);
    const numbered = /^\s*\d+[.)]\s+(.+)$/.exec(line);
    if (bullet || numbered) {
      const next = bullet ? 'ul' : 'ol';
      if (listType !== next) { if (listType) out += `</${listType}>`; out += `<${next}>`; listType = next; }
      out += `<li>${(bullet || numbered)[1]}</li>`;
    } else {
      if (listType) { out += `</${listType}>`; listType = null; }
      if (line.trim()) out += `<p>${line}</p>`;
    }
  }
  if (listType) out += `</${listType}>`;
  return out || '<p></p>';
}

function setView(view) {
  state.view = view;
  $('#chatView').classList.toggle('hidden', view !== 'chat');
  $('#composerWrap').classList.toggle('hidden', view !== 'chat');
  $('#coursesView').classList.toggle('hidden', view !== 'courses');
  $('#navChat').classList.toggle('active', view === 'chat');
  $('#navCourses').classList.toggle('active', view === 'courses');
}

function showToast(message) {
  const old = document.querySelector('.toast'); if (old) old.remove();
  const toast = document.createElement('div'); toast.className = 'toast'; toast.textContent = message;
  document.body.append(toast); setTimeout(() => toast.remove(), 3600);
}

function addMessage(role, text, sources = []) {
  const wrapper = document.createElement('article'); wrapper.className = `message ${role}`;
  const avatar = document.createElement('div'); avatar.className = 'avatar'; avatar.textContent = role === 'assistant' ? 'ИВТ' : 'ТЫ';
  const content = document.createElement('div'); content.className = 'message-content';
  const label = document.createElement('div'); label.className = 'message-label'; label.textContent = role === 'assistant' ? 'НАВИГАТОР ИВТ' : 'ТВОЙ ВОПРОС';
  const bubble = document.createElement('div'); bubble.className = 'bubble'; bubble.innerHTML = role === 'assistant' ? renderMarkdown(text) : `<p>${escapeHtml(text).replaceAll('\n', '<br>')}</p>`;
  content.append(label, bubble);
  if (role === 'assistant' && sources.length) {
    const sourceWrap = document.createElement('div'); sourceWrap.className = 'sources';
    const unique = new Set();
    sources.filter(s => s && s.url && safeUrl(s.url) && s.url.startsWith('https://www.hse.ru/') && !unique.has(s.url) && unique.add(s.url)).slice(0, 6).forEach((source, index) => {
      const link = document.createElement('a'); link.className = 'source-link'; link.href = source.url; link.target = '_blank'; link.rel = 'noopener noreferrer';
      link.textContent = `↗ ${source.title || `Источник ${index + 1}`}`; sourceWrap.append(link);
    });
    if (sourceWrap.childElementCount) content.append(sourceWrap);
  }
  wrapper.append(avatar, content); $('#messages').append(wrapper);
  $('#welcome').classList.add('hidden');
  wrapper.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

async function askQuestion(question) {
  const q = String(question || '').trim();
  if (!q || state.busy) return;
  setView('chat');
  addMessage('user', q);
  $('#questionInput').value = ''; resizeInput();
  state.busy = true; $('#sendButton').disabled = true; $('#typing').classList.remove('hidden');
  try {
    const response = await fetch('/api/ask', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ question: q, session_id: state.sessionId })
    });
    const payload = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(payload.detail || `Ошибка сервера (${response.status})`);
    addMessage('assistant', payload.answer || 'Не удалось получить ответ.', payload.sources || []);
  } catch (error) {
    addMessage('assistant', `Не удалось выполнить запрос: ${error.message}\n\nПроверь, что сервер запущен, данные собраны, а ключ Gemini настроен.`);
  } finally {
    state.busy = false; $('#sendButton').disabled = false; $('#typing').classList.add('hidden'); $('#questionInput').focus();
  }
}

function resizeInput() {
  const input = $('#questionInput'); input.style.height = 'auto'; input.style.height = `${Math.min(input.scrollHeight, 150)}px`;
}

async function loadStatus() {
  try {
    const response = await fetch('/api/status'); const status = await response.json();
    if (!response.ok) throw new Error('status');
    $('#statusDot').className = `status-dot ${status.data_ready ? 'ok' : 'bad'}`;
    $('#statusText').textContent = status.data_ready ? `Сервер работает · ${status.courses_count} дисциплин` : 'Нужно загрузить каталог';
    $('#navCourseCount').textContent = status.courses_count ?? '—';
  } catch {
    $('#statusDot').className = 'status-dot bad'; $('#statusText').textContent = 'Нет связи с API';
  }
}

function renderCourses() {
  const term = ($('#courseSearch').value || '').trim().toLocaleLowerCase('ru');
  const matching = state.courses.filter(c => `${c.title} ${c.description}`.toLocaleLowerCase('ru').includes(term));
  const grid = $('#courseGrid'); grid.innerHTML = '';
  matching.forEach((course, i) => {
    const card = document.createElement('article'); card.className = 'course-card';
    const title = escapeHtml(course.title || 'Без названия');
    const description = escapeHtml((course.description || 'На странице не выделено краткое описание.').slice(0, 260));
    const meta = [course.year, course.credits ? `${course.credits} кредита` : '', course.language].filter(Boolean);
    const url = safeUrl(course.url);
    card.innerHTML = `<div class="course-card-top"><span class="course-number">${String(i + 1).padStart(2, '0')}</span><div><h3>${title}</h3><div class="course-meta">${meta.map(v => `<span class="meta-pill">${escapeHtml(v)}</span>`).join('')}</div></div></div><p>${description}</p>${url && url.startsWith('https://www.hse.ru/') ? `<a class="course-link" href="${escapeHtml(url)}" target="_blank" rel="noopener noreferrer">Открыть официальную программу ↗</a>` : ''}`;
    grid.append(card);
  });
  $('#catalogSummary').textContent = `Найдено: ${matching.length} из ${state.courses.length}`;
  $('#courseEmpty').classList.toggle('hidden', matching.length > 0);
}

async function openCourses() {
  setView('courses'); $('#courseGrid').innerHTML = '<div class="empty-state">Загружаю каталог…</div>';
  try {
    const response = await fetch('/api/courses'); const payload = await response.json();
    state.courses = payload.courses || [];
    renderCourses();
    if (!state.courses.length) showToast(payload.message || 'Каталог пока не собран.');
  } catch { $('#courseGrid').innerHTML = ''; showToast('Не удалось загрузить каталог. Проверь сервер.'); }
}

$('#chatForm').addEventListener('submit', (event) => { event.preventDefault(); askQuestion($('#questionInput').value); });
$('#questionInput').addEventListener('input', resizeInput);
$('#questionInput').addEventListener('keydown', (event) => { if (event.key === 'Enter' && !event.shiftKey) { event.preventDefault(); $('#chatForm').requestSubmit(); } });
document.querySelectorAll('[data-question]').forEach(button => button.addEventListener('click', () => askQuestion(button.dataset.question)));
$('#navChat').addEventListener('click', () => setView('chat'));
$('#navCourses').addEventListener('click', openCourses);
$('#courseSearch').addEventListener('input', renderCourses);
$('#clearChat').addEventListener('click', () => {
  state.sessionId = `web-${crypto.randomUUID ? crypto.randomUUID() : Date.now()}`;
  localStorage.setItem('hse-assistant-session', state.sessionId.slice(4));
  $('#messages').innerHTML = ''; $('#welcome').classList.remove('hidden'); setView('chat');
  showToast('Начат новый диалог.');
});
loadStatus();
setInterval(loadStatus, 45000);
